using System;
using System.Collections.Generic;
using System.IO;
using System.Security.Cryptography;
using Newtonsoft.Json;

namespace OpenMMORPG.KitUpdater
{
    /// <summary>
    /// What <c>Tools/Install/KitManifest.json</c> says, written by <c>Tools~/build_unitypackage.py</c> into every kit archive.
    ///
    /// It lists every file and folder the release ships, keyed by GUID, with a hash of each file and of its <c>.meta</c>. The
    /// installed kit keeps the manifest of the release it came from, so comparing it with what is on disk shows exactly which
    /// kit files the user has edited, moved or deleted since.
    ///
    /// The manifest is generated by the release build and never committed, so a git checkout of the kit has none.
    /// </summary>
    public class KitManifest
    {
        public const string Guid = "b0dc8875fe2440b1b1620858e0de0436";
        /// <summary>Where the manifest sits, relative to the kit folder.</summary>
        public const string KitRelativePath = "Tools/Install/KitManifest.json";
        /// <summary>The newest <see cref="format"/> this code understands.</summary>
        public const int SupportedFormat = 1;

        public int format;
        /// <summary>"1.1.5" for a release; a branch name, or "dev", for a test build.</summary>
        public string version;
        /// <summary>The release's git tag, "v1.1.5"; null for a test build.</summary>
        public string tag;
        /// <summary>The Unity editor the release needs, "6000.3".</summary>
        public string unity;
        public Dictionary<string, string> dependencies;
        /// <summary>GUID to entry.</summary>
        public Dictionary<string, KitManifestEntry> files;

        public static KitManifest Parse(string json)
        {
            var manifest = JsonConvert.DeserializeObject<KitManifest>(json);
            if (manifest == null || manifest.files == null)
                throw new FormatException("not a kit manifest");
            if (manifest.format > SupportedFormat)
                throw new FormatException("manifest format " + manifest.format + " is newer than this kit understands (" + SupportedFormat + ")");
            return manifest;
        }
    }

    public class KitManifestEntry
    {
        /// <summary>Relative to the kit folder, with forward slashes.</summary>
        public string path;
        public bool folder;
        /// <summary>See <see cref="KitHash"/>; null for a folder.</summary>
        public string hash;
        /// <summary>The hash of the <c>.meta</c>.</summary>
        public string meta;
        public long size;
    }

    /// <summary>Dotted version numbers ("1.1.5", "v2.0", "1.8.30-pre.1"): the numbers before any "-" are compared in order.</summary>
    public static class KitVersion
    {
        /// <summary>Negative, zero or positive as <paramref name="a"/> is older, the same or newer; null if either is not a version.</summary>
        public static int? Compare(string a, string b)
        {
            int[] x = Numbers(a);
            int[] y = Numbers(b);
            if (x == null || y == null)
                return null;
            for (int i = 0; i < Math.Max(x.Length, y.Length); ++i)
            {
                int p = i < x.Length ? x[i] : 0;
                int q = i < y.Length ? y[i] : 0;
                if (p != q)
                    return p.CompareTo(q);
            }
            return 0;
        }

        private static int[] Numbers(string version)
        {
            if (string.IsNullOrEmpty(version))
                return null;
            string[] parts = version.TrimStart('v', 'V').Split('-')[0].Split('.');
            var numbers = new int[parts.Length];
            for (int i = 0; i < parts.Length; ++i)
            {
                if (!int.TryParse(parts[i], out numbers[i]))
                    return null;
            }
            return numbers;
        }
    }

    /// <summary>
    /// The path to give System.IO for a project-relative (or any) path. Unity's Mono fails on Windows paths of 260
    /// characters or more, which a kit file reaches in a project a few folders deep, though Unity itself imports it; the
    /// <c>\\?\</c> form lifts the limit.
    /// </summary>
    public static class KitPath
    {
        public static string Disk(string path)
        {
            string full = Path.GetFullPath(path);
            if (Path.DirectorySeparatorChar == '\\' && full.Length >= 240 && !full.StartsWith(@"\\", StringComparison.Ordinal))
                return @"\\?\" + full;
            return full;
        }
    }

    /// <summary>
    /// The hash the manifest records: SHA-1 of the file, with CRLF read as LF when it is text (no NUL in its first 8,000
    /// bytes), because a Windows working tree is CRLF and an exported package is not. The same rule as
    /// <c>Tools~/build_unitypackage.py</c> and the pipeline installer's <c>pipelines.json</c>.
    /// </summary>
    public static class KitHash
    {
        public static string OfFile(string absolutePath)
        {
            return Of(File.ReadAllBytes(absolutePath));
        }

        /// <summary>Drops the CR of each CRLF in place, so <paramref name="data"/> is not usable afterwards.</summary>
        public static string Of(byte[] data)
        {
            int probe = Math.Min(data.Length, 8000);
            bool text = true;
            for (int i = 0; i < probe; ++i)
            {
                if (data[i] == 0) { text = false; break; }
            }
            int length = data.Length;
            if (text)
            {
                int w = 0;
                for (int r = 0; r < data.Length; ++r)
                {
                    if (data[r] == 0x0D && r + 1 < data.Length && data[r + 1] == 0x0A)
                        continue;
                    data[w++] = data[r];
                }
                length = w;
            }
            using (SHA1 sha = SHA1.Create())
                return "sha1:" + BitConverter.ToString(sha.ComputeHash(data, 0, length)).Replace("-", "").ToLowerInvariant();
        }
    }
}
